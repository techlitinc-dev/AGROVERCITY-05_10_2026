    if not await query("expert_talks", [], limit=1):
        for item in EXPERT_TALKS:
            await set_doc("expert_talks", item["id"], item)
    if not await query("videos", [], limit=1):
        for item in VIDEOS:
            await set_doc("videos", item["id"], item)
    if not await query("blogs", [], limit=1):
        for item in BLOGS:
            await set_doc("blogs", item["id"], item)

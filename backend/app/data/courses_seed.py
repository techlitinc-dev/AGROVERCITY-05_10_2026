async def seed_courses():
    """Seed GyanSetu courses, teacher profiles, and platform ads."""
    for teacher in SEED_TEACHERS:
        existing = await get_doc("teacher_profiles", teacher["id"])
        if existing is None:
            await set_doc("teacher_profiles", teacher["id"], teacher)

    for course in SEED_COURSES:
        existing = await get_doc("courses", course["id"])
        if existing is None:
            await set_doc("courses", course["id"], course)

    for ad in SEED_ADS:
        existing = await get_doc("ad_campaigns", ad["id"])
        if existing is None:
            await set_doc("ad_campaigns", ad["id"], ad)

    logger.info("GyanSetu Superstore courses, teachers, and ads seeded successfully.")

  static final Map<String, Map<String, String>> values = _mergeValues();

  static Map<String, Map<String, String>> _mergeValues() {
    final merged = <String, Map<String, String>>{
      for (final entry in _baseValues.entries)
        entry.key: Map<String, String>.from(entry.value),
    };
    for (final table in kAllModuleTables) {
      for (final entry in table.entries) {
        merged
            .putIfAbsent(entry.key, () => <String, String>{})
            .addAll(entry.value);
      }
    }
    return merged;
  }

  static String get(String key, String langCode) {
    return values[langCode]?[key] ??
        values['en']?[key] ??
        values['hi']?[key] ??
        key;
  }
